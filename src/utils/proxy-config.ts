export interface ProxyUpstream {
  host: string;
  port: number;
}

export interface ProxyConfigOptions {
  serviceName: string;
  domain?: string;
  upstreams: ProxyUpstream[];
  rateLimitRps?: number;
  ssl?: boolean;
}

export function sanitizeProxyDomain(domain: string): string {
  const trimmed = domain.trim().toLowerCase();
  if (
    !trimmed ||
    trimmed.length > 253 ||
    trimmed.includes("..") ||
    !/^[a-z0-9](?:[a-z0-9.-]{0,251}[a-z0-9])?$/.test(trimmed)
  ) {
    throw new Error(`Security: Invalid proxy domain '${domain}'`);
  }
  return trimmed;
}

export function sanitizeProxyHost(host: string): string {
  const trimmed = host.trim();
  if (!/^[a-zA-Z0-9.:-]+$/.test(trimmed) || trimmed.length > 253) {
    throw new Error(`Security: Invalid upstream host '${host}'`);
  }
  return trimmed;
}

export function sanitizeUpstreamName(name: string): string {
  const cleaned = name.replace(/[^a-zA-Z0-9_-]/g, "_").slice(0, 64);
  if (!cleaned) {
    throw new Error("Invalid service name for upstream");
  }
  return `bs9_${cleaned}`;
}

function validateUpstreams(upstreams: ProxyUpstream[]): ProxyUpstream[] {
  if (!Array.isArray(upstreams) || upstreams.length === 0) {
    throw new Error("At least one upstream server is required");
  }
  return upstreams.map((u) => {
    const port = Number(u.port);
    if (!Number.isInteger(port) || port < 1 || port > 65535) {
      throw new Error(`Invalid upstream port '${u.port}'`);
    }
    return {
      host: sanitizeProxyHost(u.host || "127.0.0.1"),
      port,
    };
  });
}

export function generateNginxConfig(options: ProxyConfigOptions): string {
  const domain = sanitizeProxyDomain(options.domain || "localhost");
  const upstreamName = sanitizeUpstreamName(options.serviceName);
  const upstreams = validateUpstreams(options.upstreams);
  const rps = options.rateLimitRps && options.rateLimitRps > 0 ? Math.floor(options.rateLimitRps) : 50;

  const upstreamLines = upstreams
    .map((u) => `    server ${u.host}:${u.port} max_fails=3 fail_timeout=10s;`)
    .join("\n");

  const listenBlock = options.ssl
    ? `    listen 443 ssl http2;\n    # ssl_certificate /etc/letsencrypt/live/${domain}/fullchain.pem;\n    # ssl_certificate_key /etc/letsencrypt/live/${domain}/privkey.pem;`
    : `    listen 80;`;

  return `# Generated by BS9 (Bun Sentinel 9)
limit_req_zone $binary_remote_addr zone=${upstreamName}_limit:10m rate=${rps}r/s;

upstream ${upstreamName} {
${upstreamLines}
    keepalive 32;
}

server {
${listenBlock}
    server_name ${domain};

    client_max_body_size 16m;

    location / {
        limit_req zone=${upstreamName}_limit burst=${rps * 2} nodelay;
        proxy_pass http://${upstreamName};
        proxy_http_version 1.1;
        proxy_set_header Upgrade $http_upgrade;
        proxy_set_header Connection "upgrade";
        proxy_set_header Host $host;
        proxy_set_header X-Real-IP $remote_addr;
        proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
        proxy_set_header X-Forwarded-Proto $scheme;
        proxy_next_upstream error timeout http_502 http_503 http_504;
        proxy_read_timeout 60s;
    }
}
`;
}

export function generateCaddyConfig(options: ProxyConfigOptions): string {
  const domain = sanitizeProxyDomain(options.domain || "localhost");
  const upstreams = validateUpstreams(options.upstreams);
  const targets = upstreams.map((u) => `${u.host}:${u.port}`).join(" ");

  return `# Generated by BS9 (Bun Sentinel 9)
${domain} {
    encode zstd gzip
    reverse_proxy ${targets} {
        lb_policy round_robin
        health_uri /healthz
        health_interval 10s
        fail_duration 10s
        header_up X-Real-IP {remote_host}
    }
}
`;
}
